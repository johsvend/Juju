"""Merge every submission in data/submissions/ into Juju/SharedData.lua.

    python tools/merge_submissions.py

* Only the newest submission per player id counts (a re-send replaces the old).
* Bad entries are skipped; each player's weight per mob is capped (jujudata.py).
* Output is sorted, so the same input always gives the same file.
Also writes data/summary.md with a short overview.
"""
import json
import os
import re
import sys
import time
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jujudata  # noqa: E402
import jujusign  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUBMISSIONS = os.path.join(ROOT, "data", "submissions")
OUT = os.path.join(ROOT, "Juju", "SharedData.lua")
SUMMARY = os.path.join(ROOT, "data", "summary.md")


def load_all(folder):
    newest, problems = {}, []
    if not os.path.isdir(folder):
        return newest, problems
    for name in sorted(os.listdir(folder)):
        if not name.lower().endswith((".txt", ".lua")):
            continue
        path = os.path.join(folder, name)
        try:
            with open(path, encoding="utf-8", errors="replace") as f:
                sub = jujudata.parse_submission(f.read())
        except jujudata.BadData as e:
            problems.append(f"{name}: {e}")
            continue
        sub["file"] = name
        old = newest.get(sub["id"])
        if old is None or (sub["serial"], name) > (old["serial"], old["file"]):
            newest[sub["id"]] = sub
    return newest, problems


def merge(subs):
    kills = defaultdict(int)
    items = defaultdict(lambda: defaultdict(int))
    players = defaultdict(int)
    for sub in subs.values():
        for npc, m in sub["mobs"].items():
            kills[npc] += m["kills"]
            players[npc] += 1
            for item, n in m["items"].items():
                items[npc][item] += n
    return kills, items, players


def raw_entry(npc, kills, items, players):
    lst = ",".join(f"{i}:{n}" for i, n in sorted(items[npc].items()))
    return f"{kills[npc]}|{players[npc]}|{lst}"


def pack_body(subs, kills, items, players):
    """The data part of the signed text, without the version line."""
    lines = [f"{npc}={raw_entry(npc, kills, items, players)}" for npc in sorted(kills)]
    lines += [f"#{pid}={subs[pid]['serial']}" for pid in sorted(subs)]
    return "\n".join(lines)


def canonical(version, body):
    """Exactly what is signed. Juju builds the same text (Pack.lua)."""
    return f"JUJUPACK1\nversion={version}\n" + (body + "\n" if body else "")


def read_existing():
    """version, signature and data of the current SharedData.lua (to keep the
    version when nothing changed)."""
    try:
        with open(OUT, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return 0, None, None
    v = re.search(r"^J\.SHARED_VERSION = (\d+)$", text, re.M)
    sig = re.search(r'^J\.SHARED_SIG = \{ s = "([0-9a-f]+)", q = "([0-9a-f]+)" \}$', text, re.M)
    shared = re.findall(r'^\[(\d+)\]="([0-9|:,]*)",$', text, re.M)
    contrib = re.findall(r'^\["([0-9a-f]+)"\]=(\d+),$', text, re.M)
    body = "\n".join([f"{n}={r}" for n, r in sorted(shared, key=lambda x: int(x[0]))]
                     + [f"#{i}={sv}" for i, sv in sorted(contrib)])
    return (int(v.group(1)) if v else 0), ({"s": sig.group(1), "q": sig.group(2)} if sig else None), body


def write_lua(subs, kills, items, players):
    body = pack_body(subs, kills, items, players)
    old_version, old_sig, old_body = read_existing()
    key = os.environ.get("JUJU_SIGNING_KEY")
    if old_body == body and old_version and (old_sig or not key):
        version, sig = old_version, old_sig          # same data: same version, same signature
    else:
        version = max(int(time.time()), old_version + 1)
        sig = jujusign.sign(canonical(version, body).encode("ascii"), json.loads(key)) if key else None
    lines = [
        "----------------------------------------------------------------------",
        "-- Juju — community drop counts (GENERATED by tools/merge_submissions.py)",
        "-- SHARED[npcID] = \"kills|players|item:n,item:n\"",
        "-- SHARED_CONTRIB[playerId] = export serial included (so your own kills",
        "-- aren't counted twice in-game). Do not hand-edit.",
        f"-- {len(subs)} players, {len(kills)} mobs, {sum(kills.values())} kills.",
        "----------------------------------------------------------------------",
        "local _, J = ...",
        f"J.SHARED_VERSION = {version}",
    ]
    if sig:
        lines.append(f'J.SHARED_SIG = {{ s = "{sig["s"]}", q = "{sig["q"]}" }}')
    lines.append("J.SHARED = {")
    for npc in sorted(kills):
        lines.append(f'[{npc}]="{raw_entry(npc, kills, items, players)}",')
    lines.append("}")
    lines.append("J.SHARED_CONTRIB = {")
    for pid in sorted(subs):
        lines.append(f'["{pid}"]={subs[pid]["serial"]},')
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return version, sig is not None


def write_summary(subs, kills, players, problems):
    top = sorted(kills, key=lambda n: -kills[n])[:15]
    out = [
        "# Juju – fellesdata",
        "",
        f"- Spillere: **{len(subs)}**",
        f"- Mobs med data: **{len(kills)}**",
        f"- Kills totalt: **{sum(kills.values())}**",
        "",
        "## Mest data",
        "",
        "| npcID | kills | spillere |",
        "|---|---|---|",
    ]
    out += [f"| {n} | {kills[n]} | {players[n]} |" for n in top]
    if problems:
        out += ["", "## Avviste filer", ""] + [f"- {p}" for p in problems]
    with open(SUMMARY, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def main():
    subs, problems = load_all(SUBMISSIONS)
    kills, items, players = merge(subs)
    version, signed = write_lua(subs, kills, items, players)
    write_summary(subs, kills, players, problems)
    print(f"{len(subs)} spillere, {len(kills)} mobs, {sum(kills.values())} kills -> {os.path.relpath(OUT, ROOT)}"
          f" (versjon {version}, {'signert' if signed else 'IKKE signert'})")
    for p in problems:
        print("AVVIST:", p)


if __name__ == "__main__":
    main()
